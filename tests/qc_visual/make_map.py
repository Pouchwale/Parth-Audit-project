"""Writes docs/QC-VISUAL-MAP-2026-10-17.md: each QC reference file -> its format number -> the DCRS document id(s) ->
the React component that draws it -> the layout source. From refs.py (the references) and the catalogue of
catalog.mjs (what DCRS holds), so the map cannot drift from the code.

    python -I tests/qc_visual/make_map.py [--catalog FILE] [--out FILE]
"""
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import refs  # noqa: E402

ROOT = os.path.abspath(os.path.join(HERE, "..", ".."))
SEED = "frontend/src/data/seed/"


def arg(name, default=None):
    return sys.argv[sys.argv.index(name) + 1] if name in sys.argv else default


def load_catalog(path):
    if path and os.path.exists(path):
        return json.load(open(path, encoding="utf-8"))
    out = subprocess.run(
        ["node", "--no-warnings=ExperimentalWarning", os.path.join(HERE, "catalog.mjs")],
        cwd=ROOT, capture_output=True, check=True,
    ).stdout.decode("utf-8")
    return json.loads(out)


def component(doc):
    if doc["kind"] == "compliance-statement":
        return (
            "`ComplianceDetailPage` (frontend/src/pages/CompliancePage.tsx, route `#/soc/<id>`): the statement's own page, "
            "`data-print-doc`; the screen, the print and the download are this one component"
        )
    base = (
        "`LogSheetRecordView` (frontend/src/components/records/LogSheetRecordView.tsx) inside `RecordPage` "
        "(frontend/src/pages/RecordPage.tsx, route `#/record/<id>`); header block `DocumentHeader` "
        "(frontend/src/components/documents/DocumentHeader.tsx); drawn as `.paper-head` / `.paper-body` / `.paper-foot`"
    )
    extra = refs.GRID_RENDERER.get(doc["id"])
    return base + (f"; grid: {extra}" if extra else "")


def main():
    catalog = {d["id"]: d for d in load_catalog(arg("--catalog"))}
    out_path = arg("--out", os.path.join(ROOT, "docs", "QC-VISUAL-MAP-2026-10-17.md"))
    L = []
    w = L.append
    w("# QC visual parity: the map, 17-Oct-2026")
    w("")
    w("The owner, 17-Oct-2026: \"I provided PDFs from my original Word and Excel documents, convert them to PDFs if not already, "
      "and reproduce the same layout, not a redesign. ... Start by mapping each reference document to the component that renders it, "
      "then implement, compare, and fix. ... you need to work only for QC. So make sure I need same format in my audit software in QC module.\"")
    w("")
    w("This is the first step: each reference file of the owner's folder (`C:/Users/parth/Desktop/GP3 work/Audit document/QC/QC-Pdf's`, "
      f"{len(refs.REFERENCES)} files) -> its format number -> the DCRS document id(s) -> the React component that renders it -> where its layout is written. "
      "The table is generated by `tests/qc_visual/make_map.py` from `tests/qc_visual/refs.py` and the catalogue of the code (`tests/qc_visual/catalog.mjs`).")
    w("")
    w("## How a document reaches the paper")
    w("")
    w("- **One component draws the screen, the preview, the print and the downloads.** Every QC format except the three Statements of Compliance is a "
      "`log-sheet` document: `RecordPage` (a record, route `#/record/<id>`) and `DocumentRecordsPage` (the document's own page, `#/document/<id>`) "
      "both mount `LogSheetRecordView`, which draws the sheet in three parts - the header block (`DocumentHeader`, in `.paper-head`), the body "
      "(`.paper-body`: the boxes, the grid, the notes) and the foot (`.paper-foot`). Printing goes through `frontend/src/utils/print.ts` "
      "(`printDocument()` and the `beforeprint` listener: scoping to `[data-print-doc]`, the fit to A4, the `@page` orientation, `data-paper`).")
    w("- **The layout is data.** `getLogSheetLayout(id)` (frontend/src/data/seed/logSheetLayouts.ts) merges the per-family files; the plant's own change to a format "
      "(`data/formatEdits.ts`) is laid over the issued one. Nothing is drawn per document in the component, except the grid kinds named in the table "
      "(`AcrossGrid`, `AnswerAcrossGrid`, `PanelGrid`, `HeadingBox`, `BoxTable`, `PrintedTable`, `NotesBelow`, `SheetPhotos`).")
    w("- **The Statements of Compliance** are reference-only (`isReferenceOnly`): `ComplianceDetailPage` draws the statement from `complianceStatements.ts`; "
      "its paper is a Word file the owner converted to PDF.")
    w("")
    w("## Reference file -> document -> component")
    w("")
    w("Role: **ref** = a paper held against its DCRS document; **photo** = a photographed paper (looked at, never measured: score -1; the kit also wraps it into a one-page PDF); "
      "**NOT A REFERENCE** = one of DCRS's own earlier prints that the owner marked with a pen.")
    w("")
    w("| # | Reference file (owner folder) | Format no. | Role | DCRS document id(s) | Kind | Component that renders it | Layout source |")
    w("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for i, r in enumerate(refs.all_references(), 1):
        docs = [catalog.get(d) for d in r["docs"]]
        role = {"reference": "ref", "photo": "photo", "not-reference": "**NOT A REFERENCE**"}[r["role"]]
        if r["role"] == "not-reference":
            comp = "- (not compared)"
            src = "- (not compared)"
        else:
            comp = "<br>".join(component(d) for d in docs if d)
            src = "<br>".join(f"`{SEED}{refs.LAYOUT_SOURCE.get(d['id'], '?')}`" for d in docs if d)
        kinds = ", ".join(sorted({d["kind"] for d in docs if d}))
        ids = "<br>".join(f"`{d}`" for d in r["docs"])
        name = r["file"] + ("" if i <= len(refs.REFERENCES) else " (repo only)")
        note = f" - {r['note']}" if r["note"] else ""
        w(f"| {i} | {name}{note} | {r['fmt']} | {role} | {ids} | {kinds} | {comp} | {src} |")
    w("")
    w("Notes on the files:")
    w("")
    w("- Every file of the owner's folder is byte-identical to a file already in `source-documents/` (checked by SHA-256), so the kit reads the repo copies; "
      "the path of each is in `tests/qc_visual/refs.py`. The task text counted 46 files; the folder holds 44.")
    w("- `F-QC-10_Statement of Compliance (SOC) - Flexible packaging Pouch & Film.pdf` was sent under the wrong name: its pages are the **F/QC-38** statement "
      "(`soc-flexible-packaging`). The real F/QC-10 is the Shrink Sleeve file (`soc-shrink-sleeves`).")
    w("- F-QC-31 is SAP-generated and not wanted; it is not in the folder and not in DCRS.")
    w("- F/QC/11 and F/QC/12: the reference is the paper `(2)` file; the files dated 2026-10-12 are DCRS's own prints, marked by the owner with a pen.")
    w("- F-QC-32: the owner's folder holds only DCRS's own print of 10-Oct (marked); the paper is the photograph in `source-documents/` named in "
      "`docs/QC-CHECK-2026-10-14.md`, kept as a visual-only reference.")
    w("- F-QC-13 and the Gujarati F-QC-15 are photographs: compared by eye (side by side), never scored.")
    w("")
    w("## DCRS QC documents with no reference in the owner's folder")
    w("")
    w("They are not compared (nothing to hold them against); the kit still captures their blank print so a later paper can be added to `refs.py`.")
    w("")
    w("| DCRS document id | Format no. | Name | Why no reference |")
    w("| --- | --- | --- | --- |")
    why = {
        "qc-viscosity": "F-QC-30 is a photograph (WhatsApp 2.15.18 PM), not in the owner's folder",
        "qc-temperature": "F-QC-40.C is a photograph (WhatsApp 2.15.19 PM), not in the owner's folder",
        "qc-test-reliability-label": "F-QC-14 is an Excel workbook; not in the owner's folder and there is no converter on this machine",
        "qc-test-reliability-sleeve": "F-QC-14 is an Excel workbook; not in the owner's folder",
        "qc-camera-challenge-test": "its PDF is not in the owner's folder",
        "qc-inspection-printed-film": "F/QC/34: no paper on file (photographed register, not among the originals)",
        "qc-inspection-slitting": "F/QC/35: no paper on file",
        "qc-inspection-pouching": "F/QC/37: no paper on file",
        "soc-labels": "F/QC-09 is a Word file, not in the owner's folder",
    }
    held = {d for r in refs.all_references() if r["role"] in ("reference", "photo") for d in r["docs"]}
    for d in catalog.values():
        if d["id"] in held:
            continue
        w(f"| `{d['id']}` | {d['formatNo']} | {d['name'].replace('|', '/')} | {why.get(d['id'], 'no file in the owner folder')} |")
    w("")
    w("## What is compared")
    w("")
    w("A BLANK NEW record printed on A4 by the app's own print path (`beforeprint`, print media, `prefer_css_page_size`), against the paper's pages. The paper is the truth for "
      "layout, words, order, widths, borders, fonts, row counts and orientation. The owner's explicit overrides stay (REQUIREMENTS section 111 and 117): "
      "no DATE cell in the header block, every fillable box editable, F/QC/12 standard weights, carry-forward from the previous record, one F/QC/12 record per week, "
      "and the system-generated footer lines. Never invent data in a record (section 98). The kit is `tests/qc_visual/`; see its README.md.")
    w("")
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    open(out_path, "w", encoding="utf-8", newline="\n").write("\n".join(L) + "\n")
    print(f"wrote {out_path} ({len(refs.all_references())} reference rows, {len(catalog)} documents in the catalogue)")


if __name__ == "__main__":
    main()
