// THE PLANT, SIMULATED. Applies the behaviour model in
// data/seed/plantPattern.ts (generated by tools/plant_pattern.py, calibrated
// against the company's own filled specimens and its Dec-2023 GAP report) to
// a given document and calendar date.
//
// Why this exists: a register in which every reading sits on nominal, every
// check point says Yes, every lot is Accepted and every record was verified
// the same afternoon is not a well-run plant — it is an obviously synthetic
// one, and an auditor spots it in seconds. What they look for is the
// exceptions and what was done about each. So this module produces the
// exceptions a real plant produces, and every one of them carries its
// consequence with it: the remark beside the reading, the action against the
// check point, the reason beside the lot status.
//
// Two rules make it safe to build records on:
//
//  1. DETERMINISTIC. Every value is derived from a seeded PRNG whose seed
//     names exactly what it decides ("reading|qc-viscosity|viscosity|
//     2026-08-14|11"). The same date reads the same way on every device, for
//     ever — an auditor can come back to 14-Aug and find the same 21.4 Sec.
//     reading and the same remark against it.
//  2. INDEPENDENT STREAMS. Each concern draws from its own seeded stream
//     rather than one shared sequence, so adding a value in one place cannot
//     silently re-roll every other value in the record.

// ---------------------------------------------------------------------------
// primitives

/** Box-Muller, so readings are normally distributed rather than triangular. */
function normal(rng: Rng, mean: number, sd: number): number {
  const u1 = Math.max(rng.next(), 1e-9);
  const u2 = rng.next();
  return mean + sd * Math.sqrt(-2 * Math.log(u1)) * Math.cos(2 * Math.PI * u2);
}

function round(value: number, decimals: number): number {
  const f = Math.pow(10, decimals);
  return Math.round(value * f) / f;
}

function weighted<T>(rng: Rng, options: Weighted<T>[]): T {
  const total = options.reduce((s, o) => s + o.weight, 0);
  let r = rng.next() * total;
  for (const o of options) {
    r -= o.weight;
    if (r <= 0) return o.value;
  }
  return options[options.length - 1].value;
}

function daysBetween(fromISO: string, toISO: string): number {
  return Math.round((Date.parse(toISO) - Date.parse(fromISO)) / 86400000);
}

// ---------------------------------------------------------------------------
// 1. Process readings — quiet noise, with the occasional drift episode

function modelFor(documentId: string, columnKey: string): ReadingModel {
  return READING_MODELS[`${documentId}.${columnKey}`] ?? READING_MODELS[`${documentId}.*`] ?? DEFAULT_READING_MODEL;
}

interface Episode {
  from: number;
  to: number;
  shift: number; // in the column's own unit, signed
}

/**
 * Does this reading drift on this date, and if so over which rows? Decided
 * once per (document, column, date) so a run of high readings is a run —
 * which is how a real process misbehaves, and what makes the Remark column
 * believable — rather than isolated spikes.
 */
function episodeFor(documentId: string, columnKey: string, dateISO: string, rowCount: number, halfBand: number): Episode | null {
  const model = modelFor(documentId, columnKey);
  const rng = makeRng(`episode|${documentId}|${columnKey}|${dateISO}`);
  if (!rng.chance(model.episodeRate)) return null;
  const length = Math.min(rowCount, rng.int(model.minLength, model.maxLength));
  const from = rng.int(0, Math.max(0, rowCount - length));
  const magnitude = model.minShift + rng.next() * (model.maxShift - model.minShift);
  const direction = rng.chance(0.6) ? 1 : -1; // processes run hot more often than cold
  return { from, to: from + length - 1, shift: direction * magnitude * halfBand };
}

export interface ReadingOutcome {
  value: number;
  /** Outside the printed acceptance band — the app highlights these and the
   *  QC report counts them. */
  outOfBand: boolean;
}

/**
 * One reading of a banded column. `nominalOverride` is for the set-point
 * columns that have a band but no printed nominal (the lamination sheets),
 * where the job's own set-point is the centre.
 */
export function readingFor(
  documentId: string,
  dateISO: string,
  col: LogColumn,
  rowIndex: number,
  rowCount: number,
  nominalOverride?: number
): ReadingOutcome {
  const min = col.min!;
  const max = col.max!;
  const nominal = nominalOverride ?? col.nominal ?? (min + max) / 2;
  const decimals = col.decimals ?? 2;
  const halfBand = (max - min) / 2;
  const model = modelFor(documentId, col.key);
  const sd = model.sigma ?? (model.sigmaFraction ?? 0.22) * halfBand;

  const episode = episodeFor(documentId, col.key, dateISO, rowCount, halfBand);
  const drift = episode && rowIndex >= episode.from && rowIndex <= episode.to ? episode.shift : 0;

  const rng = makeRng(`reading|${documentId}|${col.key}|${dateISO}|${rowIndex}`);
  const value = round(normal(rng, nominal + drift, sd), decimals);
  return { value, outOfBand: value < min || value > max };
}

/** The explanation an operator writes beside an out-of-band reading. */
export function excursionRemarkFor(documentId: string, dateISO: string, columnKey: string): ExcursionRemark | null {
  const options = EXCURSION_REMARKS[documentId];
  if (!options || options.length === 0) return null;
  return makeRng(`excursion|${documentId}|${columnKey}|${dateISO}`).pick(options);
}

// ---------------------------------------------------------------------------
// 2. Daily Pest Control Monitoring — the check points that fail

export interface CheckpointFinding extends CheckpointIssue {
  no: number;
}

/**
 * Which of the ten check points were answered the "finding" way on this date.
 * The wording is the company's own, from its Dec-2023 GAP Analysis Report:
 * the door closer, the utility-area gap, the fly killer found switched off,
 * the missing RBS numbering, material stacked against the wall. Check points
 * 7/8/9 are NOT decided here — rodent activity comes from the separate,
 * separately calibrated catch pattern (engine/rodentPattern.ts).
 */
export function checkpointFindingsFor(dateISO: string): CheckpointFinding[] {
  const out: CheckpointFinding[] = [];
  for (const [key, model] of Object.entries(CHECKPOINT_ISSUES)) {
    const no = Number(key);
    const rng = makeRng(`checkpoint|${no}|${dateISO}`);
    if (!rng.chance(model.rate)) continue;
    out.push({ no, ...rng.pick(model.issues) });
  }
  return out;
}

// ---------------------------------------------------------------------------
// 3. QC inspection records — how the lot was dispositioned

export interface LotOutcome {
  status: string;
  reason: string;
}

export function lotOutcomeFor(documentId: string, dateISO: string): LotOutcome {
  const rng = makeRng(`lot|${documentId}|${dateISO}`);
  const spec = weighted(
    rng,
    LOT_DECISIONS.map((d) => ({ value: d, weight: d.weight }))
  );
  if (!spec.reason) return { status: spec.status, reason: "" };
  const reasons = LOT_REASONS[documentId]?.[spec.reason];
  // A lot status other than Accepted without a reason beside it is exactly
  // what validation.ts blocks on submit, so never produce one.
  if (!reasons || reasons.length === 0) return { status: "Accepted", reason: "" };
  return { status: spec.status, reason: rng.pick(reasons) };
}

// ---------------------------------------------------------------------------
// 4. The jobs that ran

export interface JobRun extends JobSpec {
  poNo: string;
  startTime: string;
  endTime: string;
  inTimeHotroom: string;
}

function clockAfter(startMinutes: number): string {
  const m = ((startMinutes % 1440) + 1440) % 1440;
  return `${String(Math.floor(m / 60)).padStart(2, "0")}:${String(m % 60).padStart(2, "0")}`;
}

/**
 * The jobs a lamination shift got through on this date, with their PO
 * numbers and clock times. Real sheets differ day to day — the same four
 * jobs at the same four times every day for a year is the tell that nobody
 * is really filling this in.
 */
export function jobsFor(dateISO: string): JobRun[] {
  const rng = makeRng(`jobs|${dateISO}`);
  const count = weighted(rng, JOBS_PER_SHIFT);
  // Rotate through the pool by date so consecutive days share some jobs (a
  // job usually runs over more than one shift) without repeating the lot.
  const offset = Math.abs(daysBetween(PO_SERIES.onDate, dateISO)) % JOB_POOL.length;
  const jobs: JobRun[] = [];
  let clock = 9 * 60 + rng.int(0, 25);
  for (let i = 0; i < count; i++) {
    const spec = JOB_POOL[(offset + i) % JOB_POOL.length];
    const run = Math.round(spec.runMinutes * (0.85 + rng.next() * 0.35));
    const start = clock;
    const end = start + run;
    // PO numbers climb with the calendar, as a real PO series does.
    const po = PO_SERIES.base + daysBetween(PO_SERIES.onDate, dateISO) * PO_SERIES.perDay + i;
    jobs.push({
      ...spec,
      poNo: String(po),
      startTime: clockAfter(start),
      endTime: clockAfter(end),
      inTimeHotroom: clockAfter(end + rng.int(5, 15)),
    });
    clock = end;
  }
  return jobs;
}

