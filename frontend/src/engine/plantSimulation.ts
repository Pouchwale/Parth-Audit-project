// 5. Service report remarks — and the findings a technician raises

export interface ServiceRemark {
  remark: string;
  finding?: { finding: string; correctiveAction: string };
}

export function serviceRemarkFor(variantKey: string | undefined, areaName: string, dateISO: string): ServiceRemark {
  const key = (variantKey ?? "").toLowerCase().includes("rodent")
    ? "rodent"
    : (variantKey ?? "").toLowerCase().includes("fly")
      ? "fly"
      : "general";
  const model = SERVICE_REMARKS[key];
  const rng = makeRng(`service|${key}|${areaName}|${dateISO}`);
  if (!rng.chance(model.findingRate)) return { remark: rng.pick(model.routine) };
  const hit = rng.pick(model.finding);
  return {
    remark: hit.remark,
    finding: hit.raisesFinding && hit.finding && hit.correctiveAction ? { finding: hit.finding, correctiveAction: hit.correctiveAction } : undefined,
  };
}

