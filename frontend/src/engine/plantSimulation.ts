// 8. From a deviation to a corrective action

export interface FindingSchedule {
  targetDate: string;
  actualDateOfAction: string | null;
  status: "Open" | "Overdue" | "Closed";
}

/**
 * When a finding raised on `observedOn` was due to be closed, and whether it
 * actually was. This is the chain an auditor follows — observation, target
 * date, action taken, closure — so some of them are late and some are still
 * open, which is what the Dashboard's "Open Corrective Actions" counts.
 */
export function findingScheduleFor(seed: string, observedOn: string, today = todayISO()): FindingSchedule {
  const rng = makeRng(`finding|${seed}|${observedOn}`);
  const targetDate = addDays(observedOn, weighted(rng, CAPA_MODEL.targetDays));
  const closure = weighted(rng, CAPA_MODEL.closure);
  if (closure === "open") {
    return { targetDate, actualDateOfAction: null, status: compareISO(targetDate, today) < 0 ? "Overdue" : "Open" };
  }
  const closedOn =
    closure === "on-time"
      ? addDays(observedOn, Math.max(1, Math.round(daysBetween(observedOn, targetDate) * (0.3 + rng.next() * 0.6))))
      : addDays(targetDate, weighted(rng, CAPA_MODEL.lateDays));
  if (compareISO(closedOn, today) > 0) {
    return { targetDate, actualDateOfAction: null, status: compareISO(targetDate, today) < 0 ? "Overdue" : "Open" };
  }
  return { targetDate, actualDateOfAction: closedOn, status: "Closed" };
}
