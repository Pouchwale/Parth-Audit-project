// 6. Who signed

export function qcSignerFor(time: string | undefined): string {
  const hour = Number((time ?? "09:00").split(":")[0]);
  return hour >= 18 || hour < 8 ? SHIFT_ROSTER.qc.night : SHIFT_ROSTER.qc.day;
}

/** Rotates the people who actually do a job, instead of always the first name in the list. */
export function rosterPick(role: "lamination" | "pestChecker" | "verifier", dateISO: string, fallback: string): string {
  const list = SHIFT_ROSTER[role];
  if (!list || list.length === 0) return fallback;
  return makeRng(`roster|${role}|${dateISO}`).pick(list);
}

