const WORDS: Record<AccountLanguage, Record<AccountKey, string>> = { en: EN, gu: GU, hi: HI };

/** Every sentence, by language, for a test to hold the three to one another. */
export const ACCOUNT_WORDS: Readonly<Record<AccountLanguage, Readonly<Record<AccountKey, string>>>> = WORDS;

/** One sentence in a language, with its {names} filled in (a name nobody gave stays as {name}). */
export function accountWord(lang: AccountLanguage, key: AccountKey, vars: Record<string, string | number> = {}): string {
  const table = WORDS[lang] ?? EN;
  return (table[key] ?? EN[key]).replace(/\{(\w+)\}/g, (whole, name: string) => (name in vars ? String(vars[name]) : whole));
}

/** The master list's name for a level ("View" for Read: the owner's word, the same level). */
export function masterLevelName(lang: AccountLanguage, level: "none" | "read" | "write" | "edit"): string {
  return accountWord(lang, `ml.level.${level}` as AccountKey);
}
